def normalize_language(language: str | None) -> str:
    if language in SUPPORTED_LANGUAGES:
        return str(language)
    return DEFAULT_LANGUAGE


def load_language(settings: QSettings | None = None) -> str:
    local_settings = settings or QSettings()
    value = local_settings.value(SETTINGS_KEY_LANGUAGE, DEFAULT_LANGUAGE)
    return normalize_language(str(value) if value is not None else DEFAULT_LANGUAGE)


def save_language(language: str, settings: QSettings | None = None) -> None:
    local_settings = settings or QSettings()
    local_settings.setValue(SETTINGS_KEY_LANGUAGE, normalize_language(language))


def ui_text(key: str, language: str, fallback: str) -> str:
    table = _TRANSLATIONS.get(key)
    if table is None:
        return fallback
    return table.get(normalize_language(language), fallback)


def install_qt_translator(app: QCoreApplication) -> QTranslator:
    translator = QTranslator(app)
    app.installTranslator(translator)
    return translator


def available_languages() -> Mapping[str, str]:
    return {
        "zh_CN": ui_text("language.zh", "zh_CN", "中文"),
        "en_US": ui_text("language.en", "en_US", "English"),
    }
